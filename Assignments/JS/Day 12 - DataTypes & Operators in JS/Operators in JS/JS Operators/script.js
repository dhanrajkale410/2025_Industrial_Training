// JS Operators 

let num1 = prompt("Enter Number 1 : ")
let num2 = prompt("Enter Number 2 : ")


console.log("1. Arithmetic Operators")
console.log("Addition : "+ (num1+num2))
console.log("Subtraction : "+ (num1-num2))
console.log("Multiplication : "+ (num1*num2))
console.log("Division : "+ (num1/num2))
console.log("Exponent : "+ (num1**num2))
console.log("Modulus : "+ (num1%num2))

console.log("2. Comparison Operators")
console.log("Greater than : "+ (num1>num2))
console.log("Less Than : "+ (num1<num2))
console.log("Greater than Equal to : "+ (num1>=num2))
console.log("Less Than Equal to : "+ (num1<=num2))
console.log("Equals to : "+ (num1==num2))
console.log("Not Equals to : "+ (num1!=num2))

console.log("3. Assignment Operators")
console.log("Simple Assignment : "+ (num1=num2))
console.log("Addition Assignment : "+ (num1+=num2))
console.log("Subtraction Assignment : "+ (num1-=num2))
console.log("Multiplication Assignment : "+ (num1*=num2))
console.log("Division Assignment : "+ (num1/=num2))
console.log("Exponent Assignment: "+ (num1**=num2))
console.log("Modulus Assignment : "+ (num1%=num2))

console.log("4. Logical Operators")
console.log("Logical AND : "+ (num1 && num2 == 10))
console.log("Logical OR : "+ ((num1 || num2) == 10))
console.log("Logical OR : "+ (num1 != num2))
